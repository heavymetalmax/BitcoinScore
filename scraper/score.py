def _extract_pi_gap(v):
    if v is None:
        return None
    while isinstance(v, dict):
        if 'gap_pct' in v:
            return v['gap_pct']
        v = v.get('value')
    return float(v) if isinstance(v, (int, float)) else None


def _map_pi_gap(v) -> int | None:
    """Continuous 0-100 mapping for Pi Cycle Gap % (eliminates step discontinuity at 20%).
    gap <= 0%   → 100 (Pi Cycle top cross confirmed)
    gap = 20%   → 50  (approaching top zone)
    gap >= 75%  → 0   (deep bear / early cycle)
    """
    gap = _extract_pi_gap(v)
    if gap is None:
        return None
    gap = float(gap)
    if gap <= 0.0:
        return 100
    if gap <= 20.0:
        return round(50.0 + (1.0 - gap / 20.0) * 50.0)
    if gap >= 75.0:
        return 0
    return round((1.0 - (gap - 20.0) / 55.0) * 50.0)


def _extract_cipherb(cb) -> tuple[int | None, int | None, int | None]:
    """Return (weekly_raw, daily_raw, blended_score) from cipherb metric.

    Applies tiered divergence adjustments on both weekly and daily timeframes:
      - double_*_div : ±18 pts (multi-peak structural exhaustion)
      - fast_*_div   : ±12 pts (momentum divergence)
      - *_divergence : ±8 pts  (regular WaveTrend divergence)
    """
    if not isinstance(cb, dict):
        return None, None, None
    val_dict = cb.get('value', cb)
    if not isinstance(val_dict, dict):
        return None, None, None
    w = val_dict.get('weekly_score')
    d = val_dict.get('daily_score')
    weekly_raw = round(w) if w is not None else None
    daily_raw  = round(d) if d is not None else None
    if w is None:
        return weekly_raw, daily_raw, None

    # Weekly divergence shifts: when a fast or double bearish divergence fires on
    # a higher price high (while raw weekly score w >= 58), it signals structural
    # top exhaustion even if raw WT1 is lower than Peak 1.
    if val_dict.get('double_bearish_div'):
        w = min(100.0, max(w + 22.0, 94.0 if w >= 58.0 else w + 22.0))
    elif val_dict.get('fast_bearish_div'):
        w = min(100.0, max(w + 16.0, 88.0 if w >= 60.0 else w + 16.0))
    elif val_dict.get('bearish_divergence') or val_dict.get('bearish_div'):
        w = min(100.0, w + 10.0)

    if val_dict.get('double_bullish_div'):
        w = max(0.0, min(w - 22.0, 4.0 if w <= 40.0 else w - 22.0))
    elif val_dict.get('fast_bullish_div'):
        w = max(0.0, min(w - 16.0, 8.0 if w <= 35.0 else w - 16.0))
    elif val_dict.get('bullish_divergence') or val_dict.get('bullish_div'):
        w = max(0.0, w - 10.0)

    if d is not None:
        # Daily divergence shifts
        if val_dict.get('daily_double_bearish_div'):
            d = min(100.0, d + 20.0)
        elif val_dict.get('daily_fast_bearish_div') or val_dict.get('fast_bear_div'):
            d = min(100.0, d + 14.0)
        elif val_dict.get('daily_bearish_div'):
            d = min(100.0, d + 8.0)

        if val_dict.get('daily_double_bullish_div'):
            d = max(0.0, d - 20.0)
        elif val_dict.get('daily_fast_bullish_div') or val_dict.get('fast_bull_div'):
            d = max(0.0, d - 14.0)
        elif val_dict.get('daily_bullish_div'):
            d = max(0.0, d - 8.0)

        blended = round(0.8 * w + 0.2 * d)
    else:
        blended = round(w)
    return weekly_raw, daily_raw, blended


def _cipherb_has_div(cb) -> bool:
    """Return True if an active divergence signal is present on Cipher B."""
    if not isinstance(cb, dict):
        return False
    val_dict = cb.get('value', cb)
    if not isinstance(val_dict, dict):
        return False
    div_keys = (
        'double_bearish_div', 'fast_bearish_div', 'bearish_divergence', 'bearish_div',
        'double_bullish_div', 'fast_bullish_div', 'bullish_divergence', 'bullish_div',
        'daily_double_bearish_div', 'daily_fast_bearish_div', 'fast_bear_div', 'daily_bearish_div',
        'daily_double_bullish_div', 'daily_fast_bullish_div', 'fast_bull_div', 'daily_bullish_div',
    )
    return any(bool(val_dict.get(k)) for k in div_keys)


_sp_history_cache: dict | None = None


def _get_metrics_history(target_date: datetime.date | None = None) -> dict[str, list[float]] | None:
    """Return recent normalized scores (last 7 days) per metric up to target_date."""
    global _sp_history_cache
    import bisect
    sp_path = 'web/sparklines.json'
    if not os.path.exists(sp_path):
        sp_path = 'data/sparklines.json'
        if not os.path.exists(sp_path):
            return None
    try:
        if _sp_history_cache is None:
            with open(sp_path, encoding='utf-8') as f:
                _sp_history_cache = json.load(f)
        dates = _sp_history_cache.get('dates', [])
        if not dates:
            return None
        target_str = target_date.isoformat() if target_date else dates[-1]
        idx = bisect.bisect_right(dates, target_str)
        if idx <= 0:
            return None
        start_idx = max(0, idx - 7)
        history = {}
        for k, v in _sp_history_cache.items():
            if k != 'dates' and isinstance(v, list):
                history[k] = [float(x) for x in v[start_idx:idx] if x is not None]
        return history
    except Exception:
        return None


def _normalize(raw_metrics: dict, target_date: datetime.date) -> dict:
    """Normalize all raw metrics to [0, 100] risk scores."""
    normalized: dict[str, int | None] = {}
    for raw_k, norm_k in _KEY_MAP.items():
        val = raw_metrics.get(raw_k)
        normalized[norm_k] = normalize_metric(norm_k, val, target_date)

    # Pi Cycle Gap
    pi_raw = (raw_metrics.get('pi_cycle')
              or raw_metrics.get('pi_cycle_gap_pct')
              or raw_metrics.get('pi_gap'))
    normalized['pi_gap'] = _map_pi_gap(pi_raw)

    # CipherB (weekly + daily blend, divergence-adjusted)
    cb = raw_metrics.get('cipherb')
    weekly_raw, daily_raw, blended = _extract_cipherb(cb)
    normalized['cipherb']         = blended
    normalized['cipherb_weekly']  = weekly_raw
    normalized['cipherb_daily']   = daily_raw

    # BTC price within current cycle (0=cycle bottom, 100=new cycle ATH)
    # Price comes from raw_metrics if available, otherwise caller must inject it separately.
    _price = raw_metrics.get('btc_price') or raw_metrics.get('price')
    normalized['btc_price_cycle'] = price_cycle_percentile(target_date, _price)

    return normalized


# ── Phase weights ─────────────────────────────────────────────────────────────

def _phase_weights(
    normalized: dict,
    prev_scores: dict | None,
    target_date: datetime.date | str | None = None,
    persist_hmm_cache: bool = True,
    ma_context: dict | None = None,
) -> tuple[float, float, float, str, int, int]:
    """
    Compute continuous phase weights (w_bot, w_neutral, w_top) summing to 1.

    w_bot: bottom_confluence.py — calibrated from CONFIRMED_BOTTOM_DATES.
    w_top: HMM-like similarity weight. It is not a calibrated probability.
           Falls back to 0.0 when model unavailable (safe: neutral wins).

    Returns (w_bot, w_neutral, w_top, phase_label, top_signal, bot_signal).
    """
    w_top, w_bot, w_neutral = 0.0, 0.0, 1.0
    top_signal, bot_signal  = 0, 0
    phase = 'NEUTRAL'

    # ── w_bot: data-driven bottom confluence ──────────────────────────────────
    try:
        confluence = compute_bottom_confluence(normalized, _load_bc_cal())
        if confluence is not None:
            w_bot      = confluence / 100.0
            bot_signal = confluence
    except Exception:
        pass

    # ── w_top: heuristic HMM similarity weight (not probability-calibrated) ──
    try:
        import os, pickle
        model_path = 'data/v3_phase_model.pkl'
        if os.path.exists(model_path):
            if model_path not in _hmm_cache:
                try:
                    from tools.train_v3_hmm_model import HMMPhaseClassifier as _hmm_cls
                except ImportError:
                    _hmm_cls = None

                class _Unpickler(pickle.Unpickler):
                    def find_class(self, module, name):
                        if name == 'HMMPhaseClassifier' and _hmm_cls is not None:
                            return _hmm_cls
                        return super().find_class(module, name)

                with open(model_path, 'rb') as f:
                    _hmm_cache[model_path] = _Unpickler(f).load()['pipeline']

            pipeline = _hmm_cache[model_path]

            METRIC_ORDER = [
                'nupl', 'mvrv_z_score', 'rhodl_ratio', 'cvdd_ratio', 'mayer_multiple',
                'asopr', 'etf_flows', 'cipherb_weekly', 'cipherb_daily', 'fear_greed', 'm2_yoy',
            ]
            import numpy as np
            vec = []
            for m in METRIC_ORDER:
                vec.append(normalized.get(m))
            for m in METRIC_ORDER:
                s_now  = normalized.get(m)
                s_prev = (prev_scores or {}).get(m)
                vec.append(s_now - s_prev if (s_now is not None and s_prev is not None) else None)
            row   = [v if v is not None else float('nan') for v in vec]
            clf = getattr(pipeline, 'named_steps', {}).get('clf')
            if clf is not None:
                clf._active_target_date = (
                    target_date.isoformat()[:10]
                    if hasattr(target_date, 'isoformat')
                    else (str(target_date)[:10] if target_date else None)
                )
                clf._persist_cache = persist_hmm_cache
            probs = pipeline.predict_proba(np.array([row], dtype=float))[0]
            w_top      = float(probs[2])  # only use top probability from HMM
            top_signal = round(w_top * 100)
    except Exception:
        pass

    # ── Data-driven top confluence (combines with HMM via max) ───────────────
    # Uses the strongest top-discriminating metrics (cipherb, nupl, mvrv, rhodl,
    # btc_price_cycle, mayer_multiple) so diminishing-return cycle tops are
    # detected even when the legacy HMM outputs a low probability.
    _cb = normalized.get('cipherb')
    _nu = normalized.get('nupl')
    _mv = normalized.get('mvrv_z_score')
    _rh = normalized.get('rhodl_ratio')
    _pc = normalized.get('btc_price_cycle')
    _mm = normalized.get('mayer_multiple')
    _vals = [v for v in [_cb, _nu, _mv, _rh, _pc, _mm] if v is not None]
    _ps = sum(_vals) / len(_vals) if _vals else 0.0
    if _vals and _ps >= 65:
        w_top_cons = min(1.0, 0.50 + (_ps - 65.0) / 25.0 * 0.50)
        if w_top_cons > w_top:
            w_top      = w_top_cons
            top_signal = round(w_top * 100)

    # ── 200D MA & 200W MA Regime Conditioning ────────────────────────────────
    # 1. Prevent false HMM TOP in early pre-bull / neutral regimes when price is
    #    barely above 200D MA (mayer_multiple < 55) and top confluence < 62.
    if _mm is not None and _mm < 55 and _ps < 62.0 and w_top > 0.35:
        w_top *= 0.65
        top_signal = round(w_top * 100)

    if ma_context:
        ma_reg = ma_context.get('ma_regime')
        r200w = ma_context.get('ma200w_ratio')
        above_200d = ma_context.get('above_dma_200')
        # 2. Mid-bull pullback below a still-rising 200D MA while well above 200W MA
        #    (e.g. Jul 2021 summer dip): dampen w_bot so it stays NEUTRAL, not BOTTOM.
        if ma_reg == 'BULL_PULLBACK':
            w_bot *= 0.75
            bot_signal = round(w_bot * 100)
        # 3. Deep accumulation below falling 200D MA and near/below 200W MA floor:
        #    confirm macro bottom regime.
        elif ma_reg == 'DEEP_ACCUMULATION' and r200w is not None and r200w <= 1.05:
            w_bot = min(1.0, w_bot * 1.12)
            bot_signal = round(w_bot * 100)
        # 4. Once price decisively reclaims 200D MA (mayer score >= 48), transition
        #    out of BOTTOM into NEUTRAL recovery.
        elif above_200d and _mm is not None and _mm >= 48 and w_bot >= BOTTOM_PHASE_THRESHOLD:
            w_bot *= 0.80
            bot_signal = round(w_bot * 100)

    # ── Normalise so w_bot + w_top + w_neutral = 1 ───────────────────────────
    total = w_bot + w_top
    if total > 1.0:
        w_bot  /= total
        w_top  /= total
        w_neutral = 0.0
    else:
        w_neutral = max(0.0, 1.0 - total)

    # Phase label (informational only — no scoring logic gates on this string)
    if w_top > 0.40 and w_top > w_bot:
        phase = 'TOP'
    elif w_bot >= BOTTOM_PHASE_THRESHOLD and w_bot > w_top:
        phase = 'BOTTOM'

    return w_bot, w_neutral, w_top, phase, top_signal, bot_signal


# ── Weighted average helper ───────────────────────────────────────────────────

def _wavg(
    group_keys: set,
    normalized: dict,
    utilities: dict,
    min_count: int = 1,
    anchor_multipliers: dict | None = None,
) -> int | None:
    total_uw = total_us = 0.0
    active = 0
    mults = anchor_multipliers or {}
    for k in group_keys:
        s = normalized.get(k)
        u = utilities.get(k, 0.5) * mults.get(k, 1.0)
        if s is not None:
            active += 1
            total_us += s * u
            total_uw += u
    return round(total_us / total_uw) if total_uw > 0 and active >= min_count else None


def assess_data_quality(normalized: dict) -> dict:
    """Classify whether basket coverage is sufficient for an actionable signal."""
    groups = {'OC': BASKET_OC, 'MS': BASKET_MS, 'MC': BASKET_MC, 'CP': BASKET_CP}
    counts = {name: sum(normalized.get(k) is not None for k in keys)
              for name, keys in groups.items()}
    coverage = {
        name: {'active': counts[name], 'total': len(keys), 'minimum': BASKET_MIN_COUNTS[name]}
        for name, keys in groups.items()
    }
    if all(counts[name] >= BASKET_MIN_COUNTS[name] for name in groups):
        status = 'valid'
    elif counts['OC'] >= 3 and counts['MS'] >= 2 and sum(counts.values()) >= 8:
        status = 'degraded'
    else:
        status = 'invalid'
    return {'status': status, 'baskets': coverage}


def compute_uncertainty(
    baskets: list,
    normalized: dict,
    utilities: dict,
    cfg: dict | None = None,
    basket_weights: list | None = None,
) -> tuple[int, int]:
    """Compute ensemble conflict score and model confidence in [0, 100].

    Parameters
    ----------
    baskets : list
        Sub-basket averages, e.g. [oc_avg, tech_avg, macro_avg].
    normalized : dict
        Normalized indicator scores (0-100).
    utilities : dict
        Per-metric relevance weights (0-1).
    cfg : dict, optional
        Calibration constants from data/v3_calibration.json ['uncertainty'].
    basket_weights : list, optional
        Total active utility weight per basket; prevents low-weight outlier
        baskets (e.g. Macro during BOTTOM) from dominating spread.

    Returns
    -------
    tuple[int, int]
        (conflict_score, confidence_score) both in [0, 100].
    """
    if cfg is None:
        cfg = {}
    spread_max = float(cfg.get('basket_spread_max', 55.0))
    std_max    = float(cfg.get('weighted_std_max', 32.0))
    w_spread   = float(cfg.get('weight_spread', 0.60))
    w_std      = float(cfg.get('weight_std', 0.40))

    valid_pairs = [
        (float(b), float(basket_weights[i]) if basket_weights and i < len(basket_weights) and basket_weights[i] is not None else 1.0)
        for i, b in enumerate(baskets)
        if b is not None and not math.isnan(b)
    ]
    if len(valid_pairs) < 2:
        return 50, 50

    if basket_weights:
        w_tot = sum(w for _, w in valid_pairs if w > 0)
        if w_tot > 0:
            w_b_mean = sum(b * w for b, w in valid_pairs if w > 0) / w_tot
            w_b_var = sum(w * ((b - w_b_mean) ** 2) for b, w in valid_pairs if w > 0) / w_tot
            basket_spread = 2.0 * math.sqrt(w_b_var)
        else:
            basket_spread = max(b for b, _ in valid_pairs) - min(b for b, _ in valid_pairs)
    else:
        basket_spread = max(b for b, _ in valid_pairs) - min(b for b, _ in valid_pairs)

    w_mean_num = 0.0
    w_sum = 0.0
    for k, s in normalized.items():
        if s is not None and not math.isnan(s):
            u = float(utilities.get(k, 0.5))
            if u > 0:
                w_mean_num += float(s) * u
                w_sum += u

    weighted_std = 0.0
    if w_sum > 0:
        w_mean = w_mean_num / w_sum
        var_num = sum(
            float(utilities.get(k, 0.5)) * ((float(s) - w_mean) ** 2)
            for k, s in normalized.items()
            if s is not None and not math.isnan(s) and float(utilities.get(k, 0.5)) > 0
        )
        weighted_std = math.sqrt(var_num / w_sum)

    spread_term = (basket_spread / spread_max) * 100.0 if spread_max > 0 else 0.0
    std_term    = (weighted_std / std_max) * 100.0 if std_max > 0 else 0.0

    conflict   = int(min(100, max(0, round(w_spread * spread_term + w_std * std_term))))
    confidence = int(min(100, max(0, 100 - conflict)))
    return conflict, confidence


# ── Main scoring function ─────────────────────────────────────────────────────

def compute_score(
    raw_metrics: dict,
    target_date: datetime.date | str | None = None,
    prev_scores: dict | None = None,
    scores_history: list | None = None,
    btc_price: float | None = None,
    persist_hmm_cache: bool = True,
    include_v5b: bool = True,
    metrics_history: dict | None = None,
) -> dict:
    """
    Compute the composite risk score for a given set of raw metric values.

    Parameters
    ----------
    raw_metrics    : dict  — raw values from live scraper or backtest reconstruction.
    target_date    : date  — used for causal normalization; defaults to today.
    prev_scores    : dict  — metric scores from N days ago (for top signal via Mahalanobis).
    scores_history : list  — [(date_str, score, phase?, w_bot?), ...] for TiZ.
    btc_price      : float — BTC price at target_date (passed through to signal).

    Returns
    -------
    dict with: final_score, phase, w_bot/w_neutral/w_top, tiz_*, oc_coherence,
               coh_factor, utilities, normalized_scores, wave_resonance, onchain_avg,
               tech_avg, top_signal, bot_signal, pi_cross, dxy_adj.
    """
    if isinstance(target_date, str):
        target_date = datetime.date.fromisoformat(target_date)
    elif target_date is None:
        target_date = datetime.date.today()

    cal = load_calibration()
    cd  = cal['coherence_dampening']
    tiz_cfg = cal['tiz']
    dxy_cfg = cal['dxy_modifier']

    # ── 1. Normalize ──────────────────────────────────────────────────────────
    # Inject btc_price so _normalize can compute btc_price_cycle
    _raw_with_price = dict(raw_metrics)
    if btc_price is not None and 'btc_price' not in _raw_with_price:
        _raw_with_price['btc_price'] = btc_price
    normalized = _normalize(_raw_with_price, target_date)

    _eff_price = _raw_with_price.get('btc_price') or _raw_with_price.get('price')
    if isinstance(_eff_price, dict):
        _eff_price = _eff_price.get('value')
    ma_context = compute_ma_context(
        target_date,
        current_price=_eff_price,
        mayer_raw=raw_metrics.get('mayer_multiple'),
    )

    # ── 2. Phase weights ──────────────────────────────────────────────────────
    if prev_scores is None:
        try:
            from scraper.scoring_v2 import _METRIC_LOOKBACK
            from scraper.wave_history import build_prev_scores_for_wave
            prev_scores = build_prev_scores_for_wave(target_date, _METRIC_LOOKBACK)
        except Exception:
            pass

    w_bot, w_neutral, w_top, phase, top_signal, bot_signal = _phase_weights(
        normalized,
        prev_scores,
        target_date=target_date,
        persist_hmm_cache=persist_hmm_cache,
        ma_context=ma_context,
    )

    # Blend HMM phase weights with halving-cycle position prior (dynamic alpha)
    w_bot, w_neutral, w_top = blend_phase_with_cycle_prior(w_bot, w_neutral, w_top, target_date)

    # Update phase label to reflect blended weights
    if w_top >= 0.40 and w_top > w_bot:
        phase = 'TOP'
    elif w_bot >= BOTTOM_PHASE_THRESHOLD and w_bot > w_top:
        phase = 'BOTTOM'
    else:
        phase = 'NEUTRAL'

    # ── 3. Wave Resonance (independent — no V2 required) ─────────────────────
    pi_raw = (raw_metrics.get('pi_cycle')
              or raw_metrics.get('pi_cycle_gap_pct')
              or raw_metrics.get('pi_gap'))
    pi_gap_pct = _extract_pi_gap(pi_raw)

    def _scalar(v):
        """Extract numeric value from either a raw number or a {value: ...} dict."""
        if isinstance(v, dict):
            v = v.get('value')
        return float(v) if isinstance(v, (int, float)) else None

    nupl_raw = _scalar(raw_metrics.get('nupl'))
    wr_overrides = {
        'nupl':           nupl_raw,  # scores.json stores nupl in % — same units as window
        'mvrv':           _scalar(raw_metrics.get('mvrv')),
        'puell':          _scalar(raw_metrics.get('puell_multiple')),
        'cvdd_ratio':     _scalar(raw_metrics.get('cvdd_ratio')),
        'mayer_multiple': _scalar(raw_metrics.get('mayer_multiple')),
        'pi_gap_pct':     pi_gap_pct,
    }
    wr_overrides = {k: v for k, v in wr_overrides.items() if v is not None}
    wr = compute_wave_resonance(
        date=target_date.isoformat(),
        raw_overrides=wr_overrides if wr_overrides else None,
    )

    # ── 4. TiZ — continuous, no phase gate ───────────────────────────────────
    if scores_history is None:
        scores_path = 'data/history/scores.json'
        if os.path.exists(scores_path):
            try:
                with open(scores_path, encoding='utf-8') as f:
                    history_data = json.load(f)
                scores_history = [
                    (r['date'], r.get('final_score'), r.get('phase'), r.get('w_bot'))
                    for r in history_data if r.get('date')
                ]
            except Exception:
                pass

    tiz_score, tiz_days, tiz_calibration = compute_tiz_causal(
        scores_history, target_date
    )
    tiz_maturity = round(tiz_days / tiz_calibration, 3) if tiz_days > 0 else None

    # ── 5. Utility weights ────────────────────────────────────────────────────
    cycle_day = halving_cycle_day_for(target_date)
    div_signal = _cipherb_has_div(raw_metrics.get('cipherb'))
    if metrics_history is None:
        metrics_history = _get_metrics_history(target_date)
    utilities = evaluate_all_utilities_continuous(
        normalized,
        w_top,
        w_bot,
        w_neutral,
        tiz_maturity=tiz_maturity,
        metrics_history=metrics_history,
        cycle_day=cycle_day,
        div_signal=div_signal,
    )

    # Dampen utility weight of stale / fallback cached metrics
    _RAW_TO_NORM = {
        'nupl': 'nupl', 'mvrv': 'mvrv_z_score', 'mvrv_z_score': 'mvrv_z_score',
        'rhodl_ratio': 'rhodl_ratio', 'cvdd_ratio': 'cvdd_ratio', 'asopr': 'asopr',
        'puell_multiple': 'puell', 'puell': 'puell', 'lth_supply_pct': 'lth_supply',
        'mayer_multiple': 'mayer_multiple', 'fear_greed': 'fear_greed',
        'm2_mom': 'm2_yoy', 'm2_yoy': 'm2_yoy', 'yield_curve': 'yield_curve_spread',
        'etf_flows': 'etf_flows', 'funding_rate': 'funding_rate', 'dxy': 'dxy',
        'cipherb': 'cipherb', 'pi_cycle': 'pi_gap',
    }
    _td = (
        datetime.date.fromisoformat(str(target_date)[:10])
        if target_date is not None else datetime.date.today()
    )
    for _rk, _nk in _RAW_TO_NORM.items():
        _entry = raw_metrics.get(_rk)
        if isinstance(_entry, dict) and _entry.get('is_fallback') and _nk in utilities:
            _mult = 0.7
            _upd = _entry.get('updated')
            if isinstance(_upd, str) and len(_upd) >= 10:
                try:
                    _age_days = (_td - datetime.date.fromisoformat(_upd[:10])).days
                    if _age_days >= 2:
                        _mult = 0.4
                except ValueError:
                    pass
            utilities[_nk] = round(float(utilities[_nk]) * _mult, 4)

    # ── 6a. Basket averages & Dynamic Utilities ──────────────────────────────
    quality = assess_data_quality(normalized)
    OC = _wavg(BASKET_OC, normalized, utilities, BASKET_MIN_COUNTS['OC'])
    MS = _wavg(BASKET_MS, normalized, utilities, BASKET_MIN_COUNTS['MS'])
    MC = _wavg(BASKET_MC, normalized, utilities, BASKET_MIN_COUNTS['MC'])
    CP = _wavg(BASKET_CP, normalized, utilities, BASKET_MIN_COUNTS['CP'])

    # Canonical sub-scores:
    # On-Chain, Technical (MS + CP), and Macro (MC + DXY)
    oc_avg    = OC
    tech_avg  = _wavg(BASKET_MS | BASKET_CP, normalized, utilities, 3)
    macro_avg = _wavg(BASKET_MC | {'dxy'}, normalized, utilities, 1)

    _bsum = lambda ks: sum(float(utilities.get(k, 0.5)) for k in ks if normalized.get(k) is not None)
    unc_cfg = cal.get('uncertainty', {})
    conflict_score, confidence_score = compute_uncertainty(
        [oc_avg, tech_avg, macro_avg],
        normalized,
        utilities,
        unc_cfg,
        basket_weights=[_bsum(BASKET_OC), _bsum(BASKET_MS | BASKET_CP), _bsum(BASKET_MC | {'dxy'})],
    )

    # ── 6b. Dynamic utility-weighted master core score ────────────────────────
    # The overall index is a pure data-driven composite across all available
    # core metrics, weighted by their context-dependent utilities U_i.
    ALL_SCORING_METRICS = BASKET_OC | BASKET_MS | BASKET_CP | BASKET_MC
    flat_avg = _wavg(ALL_SCORING_METRICS, normalized, utilities, min_count=4)
    if flat_avg is None:
        flat_avg = oc_avg or tech_avg or 50

    # ── 6c. Time-in-Zone (TiZ) in confirmed bottom phase ─────────────────────
    # TiZ only applies when in a true bottom accumulation regime (w_bot >= 0.50).
    score_tiz = flat_avg
    if phase == 'BOTTOM' and tiz_score is not None and w_bot >= BOTTOM_PHASE_THRESHOLD:
        tw = tiz_cfg['weight']  # 0.20
        score_tiz = (1.0 - tw * w_bot) * flat_avg + tw * w_bot * tiz_score

    # ── 6d. Coherence dampening — ensemble agreement ──────────────────────────
    oc_coherence = _oc_coherence(normalized)
    coh_floor = (
        cd['bottom_coh_floor'] * w_bot
        + cd['neutral_coh_floor'] * w_neutral
        + cd['top_coh_floor']    * w_top
    )
    neutral_s = (
        cd['bottom_neutral_target'] * w_bot
        + cd['neutral_neutral_target'] * w_neutral
        + cd['top_neutral_target']    * w_top
    )
    coh_factor  = round(coh_floor + (1.0 - coh_floor) * oc_coherence, 3)
    final_float = neutral_s + (score_tiz - neutral_s) * coh_factor

    # ── 6e. DXY macro modifier ────────────────────────────────────────────────
    dxy_score = normalized.get('dxy')
    dxy_adj   = 0.0
    if dxy_score is not None and dxy_cfg.get('enabled', False):
        if dxy_score > dxy_cfg['high']:
            dxy_adj = -min(dxy_cfg['max_adj'], (dxy_score - dxy_cfg['high']) * dxy_cfg['scale'])
        elif dxy_score < dxy_cfg['low']:
            dxy_adj = min(dxy_cfg['max_adj'], (dxy_cfg['low'] - dxy_score) * dxy_cfg['scale'])
        final_float += dxy_adj

    final = max(0, min(100, round(final_float)))

    # ── 6f. Pi Cycle top override ─────────────────────────────────────────────
    # pi_raw is a dict with 'cross' key during live scoring, but a plain float
    # (pi_gap_pct) during recompute from scores.json — detect both forms.
    _pi_gap_val = _extract_pi_gap(pi_raw)
    pi_cross = (
        (isinstance(pi_raw, dict) and bool(pi_raw.get('cross')))
        or (_pi_gap_val is not None and _pi_gap_val <= 0)
    )
    if pi_cross and final is not None:
        final = max(final, 85)

    # ── Raw-metric vector for Forward Risk ──────────────────────────────────
    def _s(v):
        if isinstance(v, dict): v = v.get('value')
        if isinstance(v, dict): v = v.get('value')
        return float(v) if isinstance(v, (int, float)) else None

    _cb = raw_metrics.get('cipherb')
    _cb_daily = None
    if isinstance(_cb, dict):
        _cb_inner = _cb.get('value', _cb)
        if isinstance(_cb_inner, dict):
            _cb_daily = _cb_inner.get('daily_score')

    _fr = raw_metrics.get('funding_rate')
    _fr_val = (_fr.get('value') or {}).get('avg_7d') if isinstance(_fr, dict) else None

    _lth_v = _s(raw_metrics.get('lth_supply_pct'))
    _lth_pct = (_lth_v / 21_000_000 * 100) if _lth_v is not None and _lth_v > 100 else _lth_v

    _mix_raw = {
        'btc_price':      _s(raw_metrics.get('btc_price')),
        'nupl':           _s(raw_metrics.get('nupl')),
        'mvrv':           _s(raw_metrics.get('mvrv')),
        'rhodl_ratio':    _s(raw_metrics.get('rhodl_ratio')),
        'cvdd_ratio':     _s(raw_metrics.get('cvdd_ratio')),
        'puell':          _s(raw_metrics.get('puell_multiple')),
        'cipherb_daily':  _cb_daily,
        'mayer_multiple': _s(raw_metrics.get('mayer_multiple')),
        'fear_greed':     _s(raw_metrics.get('fear_greed')),
        'funding_rate':   _fr_val,
        'm2_yoy':         _s(raw_metrics.get('m2_mom')),
        'lth_supply_pct': _lth_pct,
        'yield_curve':    _s(raw_metrics.get('yield_curve')),
        'dxy':            _s(raw_metrics.get('dxy')),
    }

    # ── Forward Risk (diagnostic prediction layer) ───────────────────────────
    # Predicts expected max drawdown over the next 365 days. Its inputs include
    # V3 context, so it is a distinct target rather than an independent signal.
    v5b_score: float | None = None
    v5b_validated = False
    if include_v5b:
        try:
            from scraper import mixing_model_b as _v5b
            _v5b_result = _v5b.predict_b(
                _mix_raw,
                target_date=target_date,
                w_top=round(w_top, 3),
                w_bot=round(w_bot, 3),
                v3_score=float(final),
            )
            if isinstance(_v5b_result, dict):
                v5b_score = _v5b_result['score']
                v5b_validated = bool(_v5b_result.get('validated'))
        except Exception as e:
            print(f'Warning: V5B (v5b_score / Outlook) failed — {e}')

    # ── Market Regime — decision layer (Outlook + Market Context) ───────────
    # Thresholds derived from 2018-2026 backtest (163x return vs 4.8x B&H).
    # Mirrors scraper/scoring_v3.py::_market_regime() — see docs/architecture.md
    # §7.2 for the full rationale and the Wait-vs-Hold distinction.
    market_regime:    str | None = None
    composite_risk:   float | None = None
    signal_agreement: float | None = None
    meta_score:       float | None = None
    decision_suppressed = quality['status'] != 'valid' or not v5b_validated
    suppression_reasons = []
    if quality['status'] != 'valid':
        suppression_reasons.append(f"data_quality_{quality['status']}")
    if not v5b_validated:
        suppression_reasons.append('v5b_not_better_than_baseline')
    if v5b_score is not None and final is not None:
        _mc = float(final)
        buy  = _mc <  35 and v5b_score <  20
        sell = _mc >= 65 and v5b_score >= 45
        hold = _mc >= 65 and v5b_score <  45
        market_regime = 'Buy' if buy else 'Sell' if sell else 'Hold' if hold else 'Wait'
        if decision_suppressed:
            market_regime = 'Unavailable' if quality['status'] == 'invalid' else 'Wait'
        # Composite risk = √(Market Context × Outlook) — display gauge only, not used in market_regime.
        composite_risk   = round(math.sqrt(max(0.0, _mc) * max(0.0, v5b_score)), 1)
        signal_agreement = round(1.0 - abs(_mc - v5b_score) / 100.0, 2)
        _w_mc  = signal_agreement / 2
        _w_v5b = 1.0 - _w_mc
        meta_score = round(_w_mc * _mc + _w_v5b * v5b_score, 1)

    return {
        'final_score':        final,
        'raw_utility_score':  round(flat_avg) if flat_avg is not None else None,
        'phase':              phase,
        'w_bot':              round(w_bot, 3),
        'w_neutral':          round(w_neutral, 3),
        'w_top':              round(w_top, 3),
        'phase_method':       'heuristic_hmm_cycle_blend',
        'phase_probabilistic': False,
        'top_signal':         top_signal,
        'bot_signal':         bot_signal,
        'onchain_avg':        round(oc_avg) if oc_avg is not None else None,
        'tech_avg':           round(tech_avg) if tech_avg is not None else None,
        'macro_avg':          round(macro_avg) if macro_avg is not None else None,
        'oc_basket':          round(OC) if OC is not None else None,
        'ms_basket':          round(MS) if MS is not None else None,
        'mc_basket':          round(MC) if MC is not None else None,
        'cp_basket':          round(CP) if CP is not None else None,
        'oc_read':            round(OC) if OC is not None else None,
        'tiz_score':          tiz_score,
        'tiz_days':           tiz_days,
        'tiz_maturity':       tiz_maturity,
        'tiz_calibration':    tiz_calibration,
        'oc_coherence':       round(oc_coherence, 3),
        'coh_factor':         coh_factor,
        'pi_cross':           pi_cross,
        'dxy_adj':            round(dxy_adj, 2),
        'ma_context':         ma_context,
        'wave_resonance':     wr,
        'utilities':          utilities,
        'v5b_score':          v5b_score,
        'v5b_validated':      v5b_validated,
        'market_regime':      market_regime,
        'score_status':       quality['status'],
        'basket_coverage':    quality['baskets'],
        'decision_suppressed': decision_suppressed,
        'decision_suppression_reason': ','.join(suppression_reasons) or None,
        'composite_risk':     composite_risk,
        'signal_agreement':   signal_agreement,
        'meta_score':         meta_score,
        'conflict_score':     conflict_score,
        'confidence_score':   confidence_score,
        'normalized_scores':  {
            k: round(v) for k, v in normalized.items()
            if v is not None and k not in ('cipherb_weekly', 'cipherb_daily')
        },
    }
